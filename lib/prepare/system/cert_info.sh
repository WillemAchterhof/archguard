#!/usr/bin/env bash
# ==============================================================================
#  Arch Secure Installer V2.6 — Secure Boot Certificate Information
# ==============================================================================
#  lib/prepare/system/cert_info.sh
#
#  Displays information about the available Secure Boot certificate modes.
#
#  Does not modify configuration.
# ==============================================================================

cert_info()
{
    clear

    printf '%s\n' "================================================================================"
    printf '%s\n' " Secure Boot Certificate Options"
    printf '%s\n\n' "================================================================================"

    printf '%s\n' " [1] Custom"
    printf '%s\n' "     Your system uses certificates generated by this installer."
    printf '\n'

    printf '%s\n' "     Before the certificates can be enrolled, the UEFI must be placed"
    printf '%s\n' "     into Setup Mode. Setup Mode means the Platform Key (PK) has been"
    printf '%s\n' "     removed, allowing new Secure Boot keys to be enrolled."
    printf '\n'

    printf '%s\n' "     Advantages:"
    printf '%s\n' "       + Maximum control over what is allowed to boot."
    printf '%s\n' "       + Only software signed with your trusted keys can boot."
    printf '%s\n' "       + No dependency on Microsoft's Secure Boot certificates."
    printf '\n'

    printf '%s\n' "     Disadvantages:"
    printf '%s\n' "       - Other unsigned or differently-signed boot media will not boot"
    printf '%s\n' "         while Secure Boot is enabled."
    printf '%s\n' "       - You are responsible for signing your own boot files."
    printf '%s\n' "       - Some hardware firmware or option ROMs may require Microsoft's"
    printf '%s\n' "         certificates to function during the pre-boot stage."
    printf '\n'

    printf '%s\n' " [2] Microsoft"
    printf '%s\n' "     Uses the Microsoft Secure Boot trust chain already provided by"
    printf '%s\n' "     the system firmware."
    printf '\n'

    printf '%s\n' "     Advantages:"
    printf '%s\n' "       + Easiest option."
    printf '%s\n' "       + No custom certificates need to be created or enrolled."
    printf '%s\n' "       + Broad compatibility with Microsoft-signed boot software."
    printf '\n'

    printf '%s\n' "     Disadvantages:"
    printf '%s\n' "       - Less restrictive than using only your own certificates."
    printf '%s\n' "       - You are trusting Microsoft's Secure Boot signing infrastructure."
    printf '%s\n' "       - You do not get the same level of control over what third-party"
    printf '%s\n' "         EFI software is trusted to boot."
    printf '\n'

    printf '%s\n' " [3] Custom with Microsoft available"
    printf '%s\n' "     Uses your own certificates while also retaining Microsoft's"
    printf '%s\n' "     certificates in the UEFI trust database."
    printf '\n'

    printf '%s\n' "     Before the certificates can be enrolled, the UEFI must be placed"
    printf '%s\n' "     into Setup Mode."
    printf '\n'

    printf '%s\n' "     Advantages:"
    printf '%s\n' "       + Your own keys control your Arch installation and its boot files."
    printf '%s\n' "       + Microsoft-signed EFI software remains trusted."
    printf '%s\n' "       + Better compatibility with other bootable media and hardware"
    printf '%s\n' "         whose pre-boot firmware is signed by Microsoft."
    printf '%s\n' "       + Good balance between security, control, and compatibility."
    printf '\n'

    printf '%s\n' "     Disadvantages:"
    printf '%s\n' "       - More setup is required than Microsoft-only."
    printf '%s\n' "       - You still trust Microsoft's Secure Boot certificates."
    printf '%s\n' "       - It does not provide the same restrictive trust boundary as"
    printf '%s\n' "         Custom-only."
    printf '\n'

    printf '%s\n' "--------------------------------------------------------------------------------"
    printf '%s\n' " Setup Mode"
    printf '%s\n' "--------------------------------------------------------------------------------"
    printf '\n'

    printf '%s\n' " Custom and Custom with Microsoft available require the UEFI to be in"
    printf '%s\n' " Setup Mode before the custom keys can be enrolled."
    printf '\n'

    printf '%s\n' " Setup Mode normally means that the Platform Key (PK) has been removed."
    printf '%s\n' " The exact procedure for entering Setup Mode depends on the motherboard"
    printf '%s\n' " or system manufacturer."
    printf '\n'

    printf '%s\n' " Microsoft-only does not require custom key enrollment."
    printf '\n'

    printf '%s\n' "================================================================================"
    printf '%s\n' " Press Enter to return"
    printf '%s\n' "================================================================================"

    read -r
}